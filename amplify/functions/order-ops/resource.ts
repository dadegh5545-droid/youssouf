import { defineFunction } from "@aws-amplify/backend";

/**
 * العمليات الحسّاسة على الطلب — اعتمادًا وتقدّمًا وسحب عيّنة ومراجعة —
 * وكتابة سجل التدقيق.
 *
 * **لماذا على الخادم لا في المتصفّح:** صلاحيات AppSync على مستوى العملية
 * لا الحقل. فمن يملك `update` على `Order` يملكه على كل حقوله معًا:
 * `status` و`approvedBy` و`discount`. أي أن مسؤول الجودة كان يستطيع — من
 * خارج الواجهة بنداء مباشر على الـ API — أن يكتب `status: APPROVED`
 * و`approvedBy` باسم زميل له، فيصدر تقرير مختبر باعتماد لم يقع ممّن نُسب
 * إليه. وشرط «أربع أعين» (من أدخل النتيجة لا يعتمدها) كان في الشاشة
 * وحدها، والشاشة لا تحكم من يتجاوزها.
 *
 * هنا تُشتقّ الهوية من `event.identity` — أي من رمز Cognito الموقَّع لا من
 * حمولة الطلب — فلا يكتب أحد باسم غيره. والتحقّق كله يعيد قراءة
 * **المخزَّن**: عدد الفحوص التي لها نتيجة محفوظة، ومن أدخل كل نتيجة،
 * والقيم الحرجة التي لم يُسجَّل إبلاغها. مسودّة الشاشة لا رأي لها.
 *
 * ويسدّ هذا عيبًا قائمًا لا ثغرة فقط: `tech` صار `read` وحده على `Order`،
 * فحفظ النتائج وتسجيل سحب العيّنة من حساب فنّي كانا يفشلان عند تحديث
 * حالة الطلب — تُحفظ النتيجة ثم تظهر رسالة «تعذّر الحفظ»، ولا يبلغ الطلب
 * `PENDING_REVIEW` فلا يظهر في قائمة الاعتماد أصلًا.
 */
export const orderOps = defineFunction({
  name: "order-ops",
  entry: "./handler.ts",
  /* الاعتماد يختم كل سطر نتيجة في الطلب: باقة كبيرة = عشرات الكتابات
     (على دفعات متزامنة). ٣٠ ثانية هامش كافٍ بلا أن يعلّق الواجهة طويلًا. */
  timeoutSeconds: 30,
});
